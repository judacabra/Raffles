export function tr(key: string, lang: "es" | "en", params?: Record<string, any>): string {
  let text = t[key]?.[lang] ?? key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    });
  }

  return text;
}
